def extra_html(url, age, limit):
    first = ("<p>Подача материала лекторами рассчитана на детей "
             "от %d&nbsp;лет.<br>\n\n"
             "Вход <b>бесплатный</b>, но необходима <a href=\"%s\" "
             "target=\"_blank\">предварительная регистрация</a>."
             % (age, url))
    if limit:
        first += " Количество мест ограничено."
    first += "</p>"
    return [
        first,
        CYCLE_PARA,
        ("<p><b>Адрес:</b> %s.<br>\n\n"
         "<b>Проезд:</b> метро «Сокол». <a href=\"%s\" target=\"_blank\">"
         "Схема проезда</a>.<br>\n\n"
         "<b>Телефон:</b> +7(495)120-05-20.</p>" % (ADDRESS, CONTACTS_URL)),
        "<!-- @@@ -->",
        ("<p class=\"small\">Информация о&nbsp;лекции <a href=\"%s\" "
         "target=\"_blank\">на сайте музея «Экспериментаниум»</a>.</p>" % url),
        PROJ_PARA,
    ]


def build(pid, date_iso, url, gen_name, field5, topics, age,
          annot, paragraphs, author, author_desc, notes, limit=True):
    """Собирает прототип: общие поля + описание + доп. информацию."""
    d = PL.d(date_iso)
    dt_end = (d + PL.datetime.timedelta(days=1))
    tail = " в&nbsp;рамках проекта «Ученые&nbsp;— детям»"
    full = "Лекция %s «%s»" % (gen_name, field5)
    # шапка: абзац 2 (автор в род. п. + название жирным + проект)
    head2 = "<p>Лекция <b><i>%s</i> «%s»</b>%s.</p>" % (gen_name, field5, tail)
    parts = [
        PL.lead_field([], date_iso, "17:00", "18:00", CITY, PLACE_SHORT, False),
        head2,
        "<KLBLOCK eltclub_authors_about/>",
        '<blockquote class="small">',
    ]
    parts += paragraphs
    parts += [
        "<p><b><i>%s</i></b>&nbsp;— <i>%s</i>.</p>" % (author, author_desc),
        "</blockquote>",
    ]
    desc_html = "\n\n".join(parts)

    fields = [PL.field("0", "ID события", pid),
              PL.field("1", "Привязка", PL.binding(date_iso, "17:00"))]
    PL.date_fields(fields, date_iso, "17:00", "18:00", CITY, PLACE_SHORT, TODAY)
    fields += [
        PL.field("3", "Полный заголовок с подзаголовком",
                 "%s<br>%s" % (SUBTITLE, full)),
        PL.field("4", "Полный заголовок без подзаголовка", full),
        PL.field("5", "Название лекции", field5),
        PL.field("6", "Подзаголовок", SUBTITLE),
        PL.field("6.1", "Тип", "Лекция"),
        PL.field("6.2", "Место (из списка)", "%s, %s" % (CITY, PLACE)),
        PL.field("6.3", "Лекторий", LECTORIUM),
        PL.field("6.4", "Тематики", ", ".join(topics)),
        PL.field("8", "Место", "%s, %s" % (CITY, PLACE_SHORT)),
        PL.field("9", "Источники", url),
        PL.field("10", "URL регистрации/покупки билета", url),
        PL.field("11", "Стоимость", "Бесплатно"),
        PL.field("12", "Возрастные ограничения", "%d+" % age),
        PL.field("13", "Адрес", ADDRESS),
        PL.field("14", "Аудитория", "Для всех, Для школьников"),
    ]

    author_fields = [
        PL.field("7.1", "Инвертированное имя",
                 "%s %s" % (author.split()[-1], author.split()[0])),
        PL.field("7.2", "Стандартное имя", author),
        PL.field("7.4", "Описание автора", "<p>%s.</p>" % author_desc),
        PL.field("7.5", "Фото из источников", ""),
        PL.field("7.6", "Файл фотографии",
                 PL.photo_file_name(author)
                 .replace("gushinec", "gushinets")
                 .replace("singkh", "singh")),
    ]

    # типографика: nbsp/«ё»-инварианты — та же механика, что в --fix.
    # Поля 2.1/2.1а/2.3/2.4 — исключение: nbsp после числа НЕ ставим
    # (post-check п. 3), поэтому их не нормализуем.
    DATE_PLAIN = ("2.1", "2.1а", "2.3", "2.4")
    for f in fields:
        if f["n"] not in ("9", "10") + DATE_PLAIN:
            f["value"] = PL.nbsp_normalize(f["value"])
    for f in author_fields:
        f["value"] = PL.nbsp_normalize(f["value"])
    desc_html = PL.nbsp_normalize(desc_html)
    annot = PL.nbsp_normalize(annot)
    field5 = PL.nbsp_normalize(field5)
    extra = [x if x in (CYCLE_PARA, PROJ_PARA) else PL.nbsp_normalize(x)
             for x in extra_html(url, age, limit)]

    proto = {
        "id": pid,
        "lectory": "«Ученые — детям»",
        "date_iso": date_iso,
        "time_start": "17:00",
        "time_end": "18:00",
        "city": CITY,
        "place": PLACE,
        "lecturer": author,
        "title": field5,
        "types": ["Лекция"],
        "topics": topics,
        "price_short": "Бесплатно",
        "annot": annot,
        "url": url,
        "sources": [url],
        "fields": fields,
        "desc_html": desc_html,
        "extra_html": extra,
        "authors": [{
            "name": author,
            "photo": "",
            "on_elementy": False,
            "block_html": PL.nbsp_normalize("<p>%s.</p>" % author_desc),
            "fields": author_fields,
        }],
        "verbatim_fragments": [CYCLE_PARA, PROJ_PARA],
        "reg_labels": [],
        "photo_file": "",
        "notes": notes,
    }
    return proto


