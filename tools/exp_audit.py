def table(pid):
    d = json.load(io.open("%s\\%s\\prototype.json" % (ROOT, pid), encoding="utf-8"))
    out = [("title", d.get("title", "")), ("annot", d.get("annot", ""))]
    for i, p in enumerate(d.get("desc_html", "").split("\n\n"), 1):
        out.append(("desc #%d" % i, p))
    for i, x in enumerate(d.get("extra_html") or [], 1):
        out.append(("extra #%d" % i, x))
    for f in d.get("fields") or []:
        out.append(("поле %s" % f["n"], f["value"]))
    for a in d.get("authors") or []:
        out.append(("block_html", a.get("block_html", "")))
        for f in a.get("fields") or []:
            out.append(("автор %s" % f["n"], f["value"]))

    def verdict(left, right):
        r = right.lstrip()
        if r.startswith("\u2015") or r.startswith("\u2014"):
            if r.startswith("\u2015"):
                return "дословная вставка 450691 — вне проверки"
            return "верно — перед тире"
        if re.search(r"(д|к|просп|ул|корп|стр|г)\.$", left):
            return "верно — адресное сокращение"
        if re.search(r"\d$", left):
            return "верно — число + слово"
        if re.search(r"(?:^|[^А-Яа-яЁё])([вскоуиаВСКОУИА])$", left):
            return "верно — однобуквенный предлог/союз"
        return "ПРОВЕРИТЬ"

    rows = []
    n = 0
    for name, t in out:
        t = t or ""
        for m in re.finditer("&nbsp;", t):
            n += 1
            left = t[max(0, m.start() - 30):m.start()]
            right = t[m.end():m.end() + 35]
            frag = re.sub(r"\s+", " ", left + "⍽" + right).strip()
            frag = frag.replace("|", "\\|")
            rows.append("| `%s` | …%s… | %s |" % (name, frag, verdict(left, right)))
    return rows, n


