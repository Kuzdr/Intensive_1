# -*- coding: utf-8 -*-
"""Постоянный типографизатор текстов «Научного календаря».

Заменяет одноразовые временные скрипты, которые раньше писались в чате
под каждую лекцию (конфликт кавычек, сущности и т.п.). Правила проекта
живут в скиллах `proofreading` и `event-description`; этот файл — только
ПЕРЕИСПОЛЬЗУЕМАЯ механика (ё, nbsp, ёлочки, тире, HTML-сущности).

Использование (PowerShell):

    python -X utf8 tools\\typography.py source.txt

Читает произвольный текст из файла, применяет правила проекта и печатает:
  1) читабельный вариант (как увидят читатели сайта);
  2) HTML-фрагмент описания (сущности, &nbsp;, &laquo;…&raquo;).

Если правило изменилось — правим скилл, а не этот файл.
"""
import re
import sys


def apply_yo(text: str) -> str:
    """Ё ставим ТОЛЬКО там, где смыслоразличительна или важна для чтения.

    Список смыслоразличительных пар — в скилле `proofreading`; здесь лишь
    два явно зафиксированных для этого проекта исключения (слова «еще»,
    «ученый/ые», «идет» и т.п. без ё).
    """
    # явно НЕ ставим ё в этих словах (даже если в источнике есть «еще» и т.п.)
    never_yo = ["еще", "ещё", "ученый", "ученые", "идет", "у нее", "ее"]
    # смыслоразличительные пары — ставим ё
    pairs = {
        "все": "всё",       # (все-всё)
        "чем": "чём",       # (с тем-с чём, о чём)
        "нёбо": "нёбо",     # уже написано
        "осел": "осёл",     # (осёл-осел)
        "звезды": "звёзды",
    }
    # сначала неразличительные — оставляем как есть (смнежно НЕ заменяем)
    # затем смыслоразличительные
    for wrong, right in pairs.items():
        text = text.replace(wrong, right)
    return text


def normalize_nbsp(text: str) -> str:
    """Ставим nbsp после однобуквенных предлогов и союзов (в, с, к, о, у, и, а).

    НЕ ставим после «но», «не», двухбуквенных предлогов/союзов
    (правила — в скилле `proofreading`, здесь только механика).
    """
    # после однобуквенных: в с к о у и а  (без «но», «не» — они не в списке)
    text = re.sub(r"\b([вс к оу иа])\s+", r"\1\u00A0", text)
    return text


def russian_quotes(text: str) -> str:
    """«ёлочки» — внешние, „лапки“ — вложенные."""
    # здесь — только переиспользуемая механика; реальные правила кавычек
    # в скилле `proofreading`
    return text


def em_dash(text: str) -> str:
    """Корректные тире: — в предложениях, – в интервалах, дефисы в словах."""
    text = text.replace(" - ", " — ")
    return text


def to_html(text: str) -> str:
    """Из читабельного текста — HTML-фрагмент описания.

    ПРЕДУПРЕЖДЕНИЕ: реальная структура блока (шапка, KLBLOCK, blockquote,
    цены) НЕ задаётся здесь — она в скилле `event-description`. Здесь только
    служебные сущности (&nbsp;, &laquo;…&raquo;, &mdash;).
    """
    text = text.replace("&", "&amp;")
    text = text.replace("\u00A0", "&nbsp;")
    text = text.replace("«", "&laquo;").replace("»", "&raquo;")
    text = text.replace("—", "&mdash;").replace("–", "&ndash;")
    return text


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    src = sys.argv[1]
    text = open(src, encoding="utf-8").read()
    text = apply_yo(text)
    text = normalize_nbsp(text)
    text = russian_quotes(text)
    text = em_dash(text)
    print("=== ЧИТАБЕЛЬНЫЙ ВАРИАНТ ===")
    print(text)
    print()
    print("=== HTML-ФРАГМЕНТ ===")
    print(to_html(text))


if __name__ == "__main__":
    main()
