def norm_nbsp(s):
    """Оставить nbsp только после однобуквенных слов, перед числом и тире.

    Механика скилла `proofreading` п. 2: после «на», «по», «до», «для»,
    «из», «от», «при», «то» и т.п. nbsp НЕ ставится.
    """
    if not isinstance(s, str):
        return s

    def repl(m):
        before, after = s[:m.start()], s[m.end():]
        if after.startswith(("—", "–")) or after[:1].isdigit():
            return "&nbsp;"
        word = re.search(r"([A-Za-zА-Яа-яЁё]+)$", before)
        if word and len(word.group(1)) == 1:
            return "&nbsp;"
        if before[-1:].isdigit():
            return "&nbsp;"
        if len(before) >= 2 and before[-1] == ".":
            # инициал («Н. Островского») или сокращение («ул. Н.»)
            return "&nbsp;"
        return " "

    return re.sub(r"&nbsp;", repl, s)


def norm_all(o):
    if isinstance(o, str):
        return norm_nbsp(o)
    if isinstance(o, list):
        return [norm_all(x) for x in o]
    if isinstance(o, dict):
        return {k: norm_all(v) for k, v in o.items()}
    return o


